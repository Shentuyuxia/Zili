// Builds data/articles.js (texts and word decks) from content/source-*.js and content/daily.js.
// Run from the repo root: npm install && npm run build
const path=require('path');
const fs=require('fs');
const ROOT=path.join(__dirname,'..');
const FILES=['source-1.js','source-2.js','source-3.js','source-4.js','daily.js'];
// Each content file exports LEX* (lexicon text) and ARTICLES* (article tuples).
const lexParts=[];
const ARTICLES=[];
for(const f of FILES){
  const p=path.join(ROOT,'content',f);
  if(!fs.existsSync(p)) continue;
  const mod=require(p);
  for(const k of Object.keys(mod)){
    if(/^LEX/.test(k)) lexParts.push(mod[k]);
    if(/^ARTICLES/.test(k)) for(const a of mod[k]) ARTICLES.push(a.length===6?a:[...a.slice(0,5),'classic']);
  }
}
const {pinyin}=require('pinyin-pro');
const O=require('opencc-js');
const toTrad=O.Converter({from:'cn',to:'tw'});
const LEX=lexParts.join('\n');
const dict=new Map();
for(const line of LEX.split('\n').map(l=>l.trim()).filter(Boolean)){
  const [w,de,en,tag]=line.split('|'); if(!dict.has(w)) dict.set(w,{de,en,tag:tag||'core'});
}
const maxLen=Math.max(...[...dict.keys()].map(k=>k.length));
const isHan=c=>/[一-鿿]/.test(c);
const missing=new Set();
const py=s=>pinyin(s,{toneType:'symbol',type:'array'}).join(' ');
function tokenize(sent){
  const out=[]; let i=0;
  while(i<sent.length){
    const c=sent[i];
    if(!isHan(c)){ out.push({s:c,t:c,p:'',punct:true}); i++; continue; }
    let hit=null;
    for(let L=Math.min(maxLen,sent.length-i);L>=1;L--){
      const w=sent.substr(i,L);
      if(dict.has(w)&&[...w].every(isHan)){ hit=w; break; }
    }
    if(!hit) hit=c;
    const g=dict.get(hit);
    if(!g) missing.add(hit);
    out.push({s:hit,t:toTrad(hit),p:py(hit),de:g?g.de:'',en:g?g.en:''});
    i+=hit.length;
  }
  return out;
}
const arts=ARTICLES.map(([id,level,audience,title,sents,topic])=>({
  id,level:+level,audience,topic,
  title:{zh:title.zh,zht:toTrad(title.zh),de:title.de,en:title.en},
  sents:sents.map(([zh,de,en])=>({tokens:tokenize(zh),zht:toTrad(zh),de,en}))
}));
const entry=w=>{const g=dict.get(w);return {w,t:toTrad(w),p:py(w),de:g.de,en:g.en}};
const deckSets={net:new Set(),young:new Set(),classic:new Set(),l1:new Set(),l2:new Set(),l3:new Set()};
for(const a of arts){
  const lk=['l1','l2','l3'][a.level-1];
  for(const s of a.sents) for(const t of s.tokens){
    if(t.punct) continue;
    if(a.topic==='net') deckSets.net.add(t.s);
    if(a.topic==='young') deckSets.young.add(t.s);
    if(a.topic==='classic') deckSets.classic.add(t.s);
    if(lk) deckSets[lk].add(t.s);
  }
}
for(const [w,g] of dict) if(g.tag==='net') deckSets.net.add(w);
for(const w of [...deckSets.net]) if(deckSets.classic.has(w)) deckSets.net.delete(w);
for(const w of [...deckSets.young]) if(deckSets.classic.has(w)||deckSets.net.has(w)) deckSets.young.delete(w);
const decks={};
for(const k in deckSets) decks[k]=[...deckSets[k]].filter(w=>dict.has(w)).map(entry);
const out=path.join(ROOT,'data','articles.js');
fs.mkdirSync(path.dirname(out),{recursive:true});
fs.writeFileSync(out,'// generated by tools/build.js from content/\nwindow.ZILI_ARTICLES='+JSON.stringify(arts)+';\nwindow.ZILI_DECKS='+JSON.stringify(decks)+';\n');
console.log('articles:',arts.length,'sentences:',arts.reduce((a,x)=>a+x.sents.length,0));
console.log('lexicon size:',dict.size,'deck sizes:',Object.entries(decks).map(([k,v])=>k+':'+v.length).join(' '));
console.log('tokens without gloss:',[...missing].join(' ')||'none');
